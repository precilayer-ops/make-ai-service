import logging
from typing import Optional
from fastapi import APIRouter, HTTPException, Query, status
from fastapi.responses import StreamingResponse

from core.gemini_client import gemini_manager
from schemas.chat import ChatRequest, ChatResponse

logger = logging.getLogger("make_ai_service.api.chat")

router = APIRouter(prefix="/chat", tags=["AI Chat & Streaming"])


@router.post(
    "",
    response_model=ChatResponse,
    summary="Generate a synchronous chat completion",
    description="Standard request/response endpoint for natural language Q&A, instructions, and conversation."
)
async def chat_completion(request: ChatRequest):
    """
    Generate a full text response for a given prompt or multi-turn message history.
    """
    if not request.prompt and (not request.messages or len(request.messages) == 0):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Either 'prompt' or 'messages' must be provided."
        )

    try:
        response = await gemini_manager.generate_chat(
            prompt=request.prompt,
            messages=request.messages,
            system_instruction=request.system_instruction,
            model=request.model,
            temperature=request.temperature
        )
        return response

    except HTTPException:
        raise
    except ValueError as e:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail=str(e))
    except Exception as e:
        logger.error(f"Error in chat_completion: {e}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"AI generation failed: {str(e)}"
        )


@router.post(
    "/stream",
    summary="Stream chat completion via Server-Sent Events (SSE)",
    description="Real-time token streaming endpoint using standard text/event-stream format. Emits JSON data chunks until done: true."
)
async def chat_stream(request: ChatRequest):
    """
    Stream word-by-word tokens as they are generated by Gemini.
    """
    if not request.prompt and (not request.messages or len(request.messages) == 0):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Either 'prompt' or 'messages' must be provided."
        )

    headers = {
        "Cache-Control": "no-cache",
        "Connection": "keep-alive",
        "Content-Type": "text/event-stream",
        "X-Accel-Buffering": "no"  # Disable Nginx response buffering
    }

    return StreamingResponse(
        gemini_manager.generate_chat_stream(
            prompt=request.prompt,
            messages=request.messages,
            system_instruction=request.system_instruction,
            model=request.model,
            temperature=request.temperature
        ),
        media_type="text/event-stream",
        headers=headers
    )


@router.get(
    "/stream/test",
    summary="Test SSE streaming directly via browser or EventSource",
    description="Convenience GET endpoint allowing quick streaming verification in browser console or curl without POST payload."
)
async def test_stream(prompt: Optional[str] = Query(default="Hello, how can you help me with manufacturing quotes?")):
    """
    Quick GET endpoint to test SSE streaming in any browser or terminal.
    """
    headers = {
        "Cache-Control": "no-cache",
        "Connection": "keep-alive",
        "Content-Type": "text/event-stream",
        "X-Accel-Buffering": "no"
    }

    return StreamingResponse(
        gemini_manager.generate_chat_stream(prompt=prompt),
        media_type="text/event-stream",
        headers=headers
    )
